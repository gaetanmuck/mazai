	<h1 class="h1">About mazai.dev</h1>

	<p>This project is a small digital playground.</p>

	<p>There is no startup idea, no product roadmap, and no grand objective behind it. It simply exists as a space to experiment, build curious things, and explore interesting concepts through code.</p>

	<p>Some projects may involve simulations, cellular automata like Conway's Game of Life, genetic algorithms, procedural generation, optimization problems, emergent systems, or visual experiments. Others may be ideas, strange prototypes, or technical rabbit holes explored just for the fun of it.</p>

	<p>The goal is not necessarily to create something useful; sometimes it is just nice to look at. Sometimes the point is simply to understand how something works, to see what happens when a few simple rules interact, or to enjoy the process of building.</p>

	<p>Think of it as a laboratory for computational curiosities and small tools.</p>

